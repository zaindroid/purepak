'use strict';
// Company-mailbox IMAP/SMTP bridge — lets a PurePak user read and send
// their own @purepak.com.pk mail inside this app instead of needing a
// separate webmail login. Nothing about the email content is ever stored
// here: every fetch is live over IMAP and every send is live over SMTP;
// only the (encrypted) mailbox password persists, in the `mailboxes` table.
const crypto = require('crypto');
const { ImapFlow } = require('imapflow');
const { simpleParser } = require('mailparser');
const nodemailer = require('nodemailer');
const MailComposer = require('nodemailer/lib/mail-composer');

// PUREPAK_MAILBOX_KEY is a 32-byte hex string (64 hex chars), generated by
// the platform the same way as other internal secrets — never typed by hand.
function encryptionKey() {
  const hex = process.env.PUREPAK_MAILBOX_KEY || '';
  if (!/^[0-9a-f]{64}$/i.test(hex)) throw new Error('PUREPAK_MAILBOX_KEY missing or malformed — must be 64 hex chars');
  return Buffer.from(hex, 'hex');
}

// AES-256-GCM, stored as base64(iv) + '.' + base64(authTag) + '.' + base64(ciphertext)
function encryptPassword(plain) {
  const key = encryptionKey();
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const ciphertext = Buffer.concat([cipher.update(String(plain), 'utf8'), cipher.final()]);
  const tag = cipher.getAuthTag();
  return `${iv.toString('base64')}.${tag.toString('base64')}.${ciphertext.toString('base64')}`;
}
function decryptPassword(stored) {
  const key = encryptionKey();
  const [ivB64, tagB64, ctB64] = String(stored).split('.');
  const iv = Buffer.from(ivB64, 'base64');
  const tag = Buffer.from(tagB64, 'base64');
  const ciphertext = Buffer.from(ctB64, 'base64');
  const decipher = crypto.createDecipheriv('aes-256-gcm', key, iv);
  decipher.setAuthTag(tag);
  return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString('utf8');
}

// one short-lived IMAP session per call — simplest safe thing given how
// infrequently a person checks mail; always logs out even on error.
async function withMailbox(mailboxRow, fn) {
  const client = new ImapFlow({
    host: mailboxRow.imap_host,
    port: mailboxRow.imap_port,
    secure: true,
    auth: { user: mailboxRow.email, pass: decryptPassword(mailboxRow.password_enc) },
    logger: false,
    socketTimeout: 15000,
  });
  await client.connect();
  try {
    return await fn(client);
  } finally {
    client.logout().catch(() => client.close());
  }
}

// quick round-trip to confirm a mailbox's email+password actually work
// before we save them — a wrong password should fail loudly right away,
// not silently the next time the inbox is opened.
async function verifyMailbox(mailboxRow) {
  await withMailbox(mailboxRow, async (client) => {
    await client.mailboxOpen('INBOX');
  });
}

// finds the real Sent folder by its IMAP SPECIAL-USE flag first (the
// server-agnostic way), falling back to the handful of names different mail
// servers use when SPECIAL-USE isn't advertised.
async function resolveSentFolder(client) {
  const list = await client.list();
  const bySpecialUse = list.find(f => f.specialUse === '\\Sent');
  if (bySpecialUse) return bySpecialUse.path;
  const names = new Set(list.map(f => f.path));
  for (const candidate of ['Sent', 'INBOX.Sent', 'Sent Items', 'INBOX/Sent']) {
    if (names.has(candidate)) return candidate;
  }
  return null;
}

async function listMessages(mailboxRow, limit = 30, folder = 'INBOX') {
  return withMailbox(mailboxRow, async (client) => {
    const mailboxName = folder === 'SENT' ? await resolveSentFolder(client) : folder;
    if (!mailboxName) return [];
    const box = await client.mailboxOpen(mailboxName);
    const total = box.exists;
    if (total === 0) return [];
    const from = Math.max(1, total - limit + 1);
    const out = [];
    for await (const msg of client.fetch(`${from}:*`, { envelope: true, flags: true, uid: true, bodyStructure: true })) {
      const addr = (list) => (list && list[0] ? (list[0].name || list[0].address) : '');
      out.push({
        uid: msg.uid,
        subject: (msg.envelope && msg.envelope.subject) || '(no subject)',
        from: addr(msg.envelope && msg.envelope.from) || 'Unknown sender',
        to: addr(msg.envelope && msg.envelope.to),
        date: msg.envelope && msg.envelope.date ? new Date(msg.envelope.date).toISOString() : null,
        unread: !msg.flags || !msg.flags.has('\\Seen'),
      });
    }
    out.reverse(); // newest first
    return out;
  });
}

async function readMessage(mailboxRow, uid, folder = 'INBOX') {
  return withMailbox(mailboxRow, async (client) => {
    const mailboxName = folder === 'SENT' ? await resolveSentFolder(client) : folder;
    if (!mailboxName) throw new Error('Folder not found');
    await client.mailboxOpen(mailboxName);
    const { content } = await client.download(uid, undefined, { uid: true });
    const parsed = await simpleParser(content);
    if (folder !== 'SENT') await client.messageFlagsAdd({ uid: String(uid) }, ['\\Seen'], { uid: true }).catch(() => {});
    return {
      uid,
      subject: parsed.subject || '(no subject)',
      from: parsed.from ? parsed.from.text : 'Unknown sender',
      to: parsed.to ? parsed.to.text : '',
      date: parsed.date ? parsed.date.toISOString() : null,
      html: parsed.html || null,
      text: parsed.text || '',
    };
  });
}

// composes one MIME message so the exact same bytes go out over SMTP and
// get archived into the Sent folder over IMAP afterward.
function buildRaw({ from, to, subject, text, html }) {
  return new Promise((resolve, reject) => {
    new MailComposer({ from, to, subject, text, html }).compile().build((err, message) => {
      if (err) reject(err); else resolve(message);
    });
  });
}

async function sendMail(mailboxRow, { to, subject, text, html }) {
  const password = decryptPassword(mailboxRow.password_enc);
  const raw = await buildRaw({ from: mailboxRow.email, to, subject, text, html });
  const transporter = nodemailer.createTransport({
    host: mailboxRow.smtp_host || mailboxRow.imap_host,
    port: 465,
    secure: true,
    auth: { user: mailboxRow.email, pass: password },
    connectionTimeout: 15000,
  });
  await transporter.sendMail({ raw, envelope: { from: mailboxRow.email, to } });
  // best-effort copy into Sent — sending already succeeded by this point, so
  // a failure here never fails the overall send, it just means the Sent
  // view might miss this one entry if the server doesn't auto-copy either
  await withMailbox(mailboxRow, async (client) => {
    const sentFolder = await resolveSentFolder(client);
    if (sentFolder) await client.append(sentFolder, raw, ['\\Seen']);
  }).catch(() => {});
}

module.exports = { encryptPassword, decryptPassword, verifyMailbox, listMessages, readMessage, sendMail };
